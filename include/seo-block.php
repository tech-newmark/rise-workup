<h2>О компании</h2>
<p>
  RISE — петербургский производитель сумок, рюкзаков и аксессуаров с опытом работы с 1999 года. Компания ООО РАЙС создает практичные и современные изделия для города, учебы, работы, поездок, спорта, мероприятий и корпоративных задач. В ассортименте есть готовые модели для розничных покупателей, оптовых клиентов, магазинов, маркетплейсов и компаний.
</p>
<p>
  Мы разрабатываем сумки и рюкзаки с учетом реального повседневного использования: удобной формы, прочных материалов, надежной фурнитуры, актуальных цветов и продуманной внутренней организации. В каталоге можно выбрать городские, школьные, спортивные, дорожные, молодежные модели, шопперы, поясные сумки, папки и другие аксессуары.
</p>
<p>
  RISE также выполняет пошив изделий на заказ и производство брендированной продукции с логотипом для промоакций, конференций, корпоративных подарков и оптовых поставок. Мы работаем с партиями под задачи клиента, помогаем подобрать подходящие модели и организуем доставку по Санкт-Петербургу и регионам России.
</p>
